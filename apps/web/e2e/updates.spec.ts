import { test, expect } from '@playwright/test';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

test('production pool update, missing input retry, frozen experiment and persisted browser facts', async ({ page }) => {
  test.setTimeout(180_000);
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  const lake = join(process.env.PRAJNA_E2E_ROOT!, 'fixture', 'lake');
  const configFile = join(lake, 'pool-updates', 'configs', 'synthetic.json');
  const configured = await readFile(configFile, 'utf8');
  const registry = (await (await page.request.get('/api/v1/research-pools')).json()).data;
  const pool = registry.pools.find((p: { id: string }) => p.id === 'bonds');
  const members = ['159952.XSHE', '510300.XSHG'];
  expect((await page.request.post('/api/v1/research-pools', { data: { op: 'save', id: 'bonds', expected: pool.draft, members } })).ok()).toBeTruthy();
  expect((await page.request.post('/api/v1/research-pools', { data: { op: 'publish', id: 'bonds', expected: members } })).ok()).toBeTruthy();
  await page.goto('/pools');
  await page.getByLabel('研究池', { exact: true }).selectOption('bonds');
  await page.getByLabel('固定版本', { exact: true }).selectOption('2');
  await page.getByLabel('本机更新配置', { exact: true }).selectOption('synthetic');
  await page.getByRole('button', { name: '更新选定池', exact: true }).click();
  const first = page.getByTestId('pool-update-attempt').first();
  await expect(first.getByTestId('update-readiness')).toContainText('价格研究输入：已就绪', { timeout: 60_000 });
  await expect(first).toContainText('159952.XSHE');
  await expect(first).toContainText('510300.XSHG');
  await expect(first).toContainText('2026-01-05 ～ 2026-01-07 · 3 条');
  await first.getByRole('button', { name: '使用此固定版本研究', exact: true }).click();
  await expect(page.getByLabel('研究池 Dataset', { exact: true })).toHaveValue(/^dsv:sha256:[a-f0-9]{64}$/);
  const fixedDsv = await page.getByLabel('研究池 Dataset', { exact: true }).inputValue();
  await page.getByLabel('预检策略', { exact: true }).selectOption('buy_and_hold');
  await page.getByLabel('参数组合 JSON', { exact: true }).fill('{"list":[{"params_version":1}]}');
  await page.getByRole('button', { name: '预检共同窗口', exact: true }).click();
  await expect(page.getByTestId('pool-preflight').getByText('可运行', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '提交固定池实验', exact: true }).click();
  const link = page.getByRole('link', { name: '查看固定池任务', exact: true });
  await expect(link).toBeVisible();
  const taskId = new URL((await link.getAttribute('href'))!, 'http://localhost').searchParams.get('task')!;
  const definitionPath = join(lake, 'tasks', taskId, 'experiment.json');
  const frozen = await readFile(definitionPath, 'utf8');
  expect(JSON.parse(frozen).dsv).toBe(fixedDsv);
  // A new attempt consumes a new supplier snapshot. The old ready attempt remains readable.
  const missing: { start: string; members: Record<string, { adjusted_file: string | null }>; actions_file: string | null } = JSON.parse(configured);
  missing.members['159952.XSHE'].adjusted_file = null;
  missing.actions_file = null;
  await writeFile(configFile, JSON.stringify(missing));
  await page.getByRole('button', { name: '更新选定池', exact: true }).click();
  await expect(page.getByTestId('pool-update-attempt')).toHaveCount(2);
  await expect(first.getByTestId('update-readiness')).toContainText('价格研究输入：待补充', { timeout: 60_000 });
  await expect(first.getByTestId('update-readiness')).toContainText('原始池行情：已发布');
  await expect(first).toContainText('succeeded');
  await expect(page.getByTestId('update-last-success')).toContainText(fixedDsv);
  await expect(first.getByRole('button', { name: '使用此固定版本研究', exact: true })).toBeDisabled();
  const failedId = await first.getAttribute('data-attempt');
  const failed = (await (await page.request.get('/api/v1/pool-updates')).json()).data.attempts.find((a: { id: string }) => a.id === failedId);
  missing.start = '2026-01-06';
  await writeFile(configFile, JSON.stringify(missing));
  await first.getByRole('button', { name: '补跑本计划', exact: true }).click();
  await expect(page.getByText('retry configuration changes fixed plan scope', { exact: false })).toBeVisible();
  await expect(page.getByTestId('pool-update-attempt')).toHaveCount(2);
  await writeFile(configFile, configured);
  await first.getByRole('button', { name: '补跑本计划', exact: true }).click();
  await expect(page.getByTestId('pool-update-attempt')).toHaveCount(3);
  await expect(first.getByTestId('update-readiness')).toContainText('价格研究输入：已就绪', { timeout: 60_000 });
  await expect(first).toContainText(`显式复用尝试 ${failedId}`);
  await expect(first.getByTestId('update-readiness')).toContainText('行动覆盖：范围已覆盖');
  const retriedId = await first.getAttribute('data-attempt');
  const retried = (await (await page.request.get('/api/v1/pool-updates')).json()).data.attempts.find((a: { id: string }) => a.id === retriedId);
  expect(retried.plan).toBe(failed.plan);
  expect(await readFile(definitionPath, 'utf8')).toBe(frozen);
  await page.reload();
  await expect(page.getByTestId('pool-update-attempt').first()).toHaveAttribute('data-attempt', retriedId!);
  await expect(page.getByTestId('pool-update-attempt').nth(1).getByTestId('update-readiness')).toContainText('待补充');
  await expect(page.getByTestId('pool-update-attempt').first().getByTestId('update-readiness')).toContainText('已就绪');
  await page.goto(`/backtests?task=${encodeURIComponent(taskId)}`);
  await expect(page.getByTestId('task-status')).toContainText('已完成', { timeout: 60_000 });
  const result = await (await page.request.get(`/api/v1/tasks/experiments/${taskId}/result`)).json();
  const final = result.data.runs[0].series.account_valuations.find((r: { session_date: string; valuation_point: string }) => r.session_date === '2026-01-07' && r.valuation_point === 'close');
  // Two equal initial budgets buy 99,900 total units at 10.002. Fees 299.75994.
  expect(final.cash).toBe('500.44006');
  expect(final.equity).toBe('1009490.44006');
  expect(final.dividend_receivable).toBe('0');
  expect(await readFile(definitionPath, 'utf8')).toBe(frozen);
  expect(errors).toEqual([]);
});

test('update API rejects foreign origins, paths, direct execution and legacy-route bypass', async ({ request }) => {
  expect((await request.get('/api/v1/pool-updates', { headers: { Origin: 'https://foreign.invalid' } })).status()).toBe(403);
  expect((await request.post('/api/v1/pool-updates', { data: { op: 'pool_update', attempt: 'invalid' } })).status()).toBe(400);
  expect((await request.post('/api/v1/pool-updates', { data: { op: 'prepare', config: '../synthetic' } })).status()).toBe(422);
  expect((await request.post('/api/v1/tasks/experiments', { data: { idempotency_key: 'no-bypass', definition: { op: 'pool_update', attempt: 'invalid' } } })).status()).toBe(400);
  expect((await request.get('/api/v1/pool-updates')).headers()['cache-control']).toBe('no-store');
});
